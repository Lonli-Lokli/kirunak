// tasks.txt and tasks.tsv (gulnya/k-usage AC-2, D-3): the week's weight per kirunak task and per step. Each call is
// weighed as the summary weighs it (common.mjs's weight: Opus base-input tokens) and joined to its task and step by
// tasks.mjs's joinOf; an agent counts with its session at its first call, so a step's agent stays the step's though it
// outlives the step. Heaviest first, each task then its steps (`no step` for its session's calls between them), the
// calls in no task last; the rows sum to the summary's weight.
// A task's `no step` row is split by what its session was doing (gulnya/usage-improve-11-22 AC-11): each no-step call
// (an agent's at its first call) takes the kind of its session's latest mark at or before it (calls.jsonl's mark rows of
// the main session, calls.mjs), a step of the session ending counting as a step follow-up mark; no mark yet is `other`.
import { writeFileSync } from 'node:fs';
import { printer, weight } from './common.mjs';
import { joinOf } from './tasks.mjs';

export const NO_TASK = 'no task';
export const NO_STEP = 'no step';
export const KINDS = ['intake', 'review and merge', 'k-done', 'step follow-up', 'other'];

// A mark's kind: `intake` (k-intake, `k intake`), `review and merge` (k-bugs, `k bug review`, a `git merge`, a review
// step's `k run --once`), `k-done` (k-done, `k accept`), `step follow-up` (`k step finish|fail`); anything else, a
// /clear and k start among them, `other`. A command or skill counts by its name, a plugin's prefix (`x:`) dropped.
export function kindOf(what) {
  const name = /^(?:\/|skill )(?:[^:\s]+:)?(\S+)$/.exec(what)?.[1];
  if (name === 'k-intake' || what === 'k intake') return 'intake';
  if (name === 'k-bugs' || ['k bug review', 'git merge', 'k run --once'].includes(what)) return 'review and merge';
  if (name === 'k-done' || what === 'k accept') return 'k-done';
  if (what === 'k step finish' || what === 'k step fail') return 'step follow-up';
  return 'other';
}

const heaviest = (a, b) => b.weight - a.weight || (a.name < b.name ? -1 : a.name > b.name ? 1 : 0);

// `rows` are calls.jsonl's rows, `tasks` readTasks's, `home` $KIRUNAK_HOME (its sessions/). Writes `tsv` when given;
// returns { total, calls, tasks: [{ name, weight, calls, steps: [{ name, weight, calls }] }], noTask, text }.
export function byTask({ rows, tasks, home, from: FROM, to: TO, tsv = null }) {
  const xs = rows.filter((c) => c.kind === 'call' && c.model !== '<synthetic>' && c.ts >= FROM && c.ts < TO);
  const of = joinOf({ tasks, home, sessions: new Set(xs.map((c) => c.session)) });
  const first = new Map();
  for (const c of xs.filter((c) => c.sub)) {
    const a = `${c.session}/${c.sub}`;
    if (!first.has(a) || c.ts < first.get(a)) first.set(a, c.ts);
  }
  // Each session's marks and its steps' ends, in time order, a step's end before a mark of the same moment.
  const marks = new Map();
  for (const m of rows.filter((r) => r.kind === 'mark' && !r.sub && r.ts < TO)) {
    if (!marks.has(m.session)) marks.set(m.session, []);
    marks.get(m.session).push({ at: Date.parse(m.ts), end: false, kind: kindOf(m.what) });
  }
  const timeline = new Map();
  const kindAt = (session, at) => {
    if (!timeline.has(session)) {
      const xs = [...(of.stepEnds(session).map((e) => ({ at: e, end: true, kind: 'step follow-up' }))), ...(marks.get(session) || [])];
      timeline.set(session, xs.sort((a, b) => a.at - b.at || b.end - a.end));
    }
    let k = 'other';
    for (const x of timeline.get(session)) if (x.at <= at) k = x.kind; else break;
    return k;
  };
  const byId = new Map(), noTask = { name: NO_TASK, weight: 0, calls: 0 };
  let total = 0;
  for (const c of xs) {
    const w = weight(c), at = Date.parse(c.sub ? first.get(`${c.session}/${c.sub}`) : c.ts);
    const { task, step } = of(c.session, at);
    total += w;
    const rs = [noTask];
    if (task) {
      if (!byId.has(task)) byId.set(task, { name: task, weight: 0, calls: 0, steps: new Map() });
      const t = byId.get(task), s = step || NO_STEP;
      if (!t.steps.has(s)) t.steps.set(s, { name: s, weight: 0, calls: 0, ...(step ? {} : { kinds: new Map(KINDS.map((k) => [k, { name: k, weight: 0, calls: 0 }])) }) });
      rs.splice(0, 1, t, t.steps.get(s));
      if (!step) rs.push(t.steps.get(s).kinds.get(kindAt(c.session, at)));
    }
    for (const r of rs) r.weight += w, r.calls++;
  }
  const list = [...byId.values()].map((t) => ({ ...t, steps: [...t.steps.values()].map((s) => (s.kinds ? { ...s, kinds: [...s.kinds.values()] } : s)).sort(heaviest) })).sort(heaviest);

  if (tsv) {
    // The no-step row is its five kinds' rows (AC-11), so the rows still sum to the week.
    const leaf = [...list.flatMap((t) => t.steps.flatMap((s) => (s.kinds ? s.kinds.map((k) => [t.name, s.name, k.name, k]) : [[t.name, s.name, '', s]]))), [NO_TASK, '', '', noTask]];
    writeFileSync(tsv, [`# generated by k usage --from ${FROM} --to ${TO} (gulnya/k-usage AC-2, gulnya/usage-improve-11-22 AC-11): a row per task and step, a task's no-step weight a row per kind, so the weights sum to the week's; never edited by hand`,
      ['task', 'step', 'kind', 'weight', 'calls'].join('\t'), ...leaf.map(([t, s, kd, r]) => [t, s, kd, Math.round(r.weight), r.calls].join('\t'))].join('\n') + '\n');
  }

  const p = printer();
  const width = Math.max(NO_TASK.length, ...list.map((t) => t.name.length), ...list.flatMap((t) => t.steps.map((s) => s.name.length + 2)), ...(list.length ? KINDS.map((k) => k.length + 4) : []));
  const line = (name, r) => `${name.padEnd(width)}  ${`${(r.weight / 1e6).toFixed(1)}M`.padStart(8)}  ${`${(total ? (100 * r.weight) / total : 0).toFixed(1)}%`.padStart(6)}  ${String(r.calls).padStart(6)} calls`;
  p.log(`by task and step, heaviest first: weight in Opus-input tokens, share of the week's ${(total / 1e6).toFixed(1)}M, calls (${xs.length}), ${of.skipped} links.jsonl lines skipped`);
  for (const t of list) {
    p.log(line(t.name, t));
    for (const s of t.steps) {
      p.log(line(`  ${s.name}`, s));
      for (const k of s.kinds || []) p.log(line(`    ${k.name}`, k));
    }
  }
  p.log(line(NO_TASK, noTask));
  return { total, calls: xs.length, tasks: list, noTask, text: p.text() };
}

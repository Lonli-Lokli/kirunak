// tasks.txt and tasks.tsv (gulnya/k-usage AC-2, D-3): the week's weight per kirunak task and per step. Each call is
// weighed as the summary weighs it (common.mjs's weight: Opus base-input tokens) and joined to its task and step by
// tasks.mjs's joinOf; an agent counts with its session at its first call, so a step's agent stays the step's though it
// outlives the step. Heaviest first, each task then its steps (`no step` for its session's calls between them), the
// calls in no task last; the rows sum to the summary's weight.
import { writeFileSync } from 'node:fs';
import { printer, weight } from './common.mjs';
import { joinOf } from './tasks.mjs';

export const NO_TASK = 'no task';
export const NO_STEP = 'no step';

const heaviest = (a, b) => b.weight - a.weight || (a.name < b.name ? -1 : a.name > b.name ? 1 : 0);

// `rows` are calls.jsonl's rows, `tasks` readTasks's, `home` $KIRUNAK_HOME (its sessions/). Writes `tsv` when given;
// returns { total, calls, tasks: [{ name, weight, calls, steps: [{ name, weight, calls }] }], noTask, text }.
export function byTask({ rows, tasks, home, from: FROM, to: TO, tsv = null }) {
  const xs = rows.filter((c) => c.kind === 'call' && c.model !== '<synthetic>' && c.ts >= FROM && c.ts < TO);
  const of = joinOf({ tasks, home, sessions: new Set(xs.map((c) => c.session)) });
  const first = new Map();
  for (const c of xs.filter((c) => c.sub)) {
    const a = `${c.session}/${c.sub}`;
    if (!first.has(a) || c.ts < first.get(a)) first.set(a, c.ts);
  }
  const byId = new Map(), noTask = { name: NO_TASK, weight: 0, calls: 0 };
  let total = 0;
  for (const c of xs) {
    const w = weight(c), at = Date.parse(c.sub ? first.get(`${c.session}/${c.sub}`) : c.ts);
    const { task, step } = of(c.session, at);
    total += w;
    const rs = [noTask];
    if (task) {
      if (!byId.has(task)) byId.set(task, { name: task, weight: 0, calls: 0, steps: new Map() });
      const t = byId.get(task), s = step || NO_STEP;
      if (!t.steps.has(s)) t.steps.set(s, { name: s, weight: 0, calls: 0 });
      rs.splice(0, 1, t, t.steps.get(s));
    }
    for (const r of rs) r.weight += w, r.calls++;
  }
  const list = [...byId.values()].map((t) => ({ ...t, steps: [...t.steps.values()].sort(heaviest) })).sort(heaviest);

  if (tsv) {
    const leaf = [...list.flatMap((t) => t.steps.map((s) => [t.name, s.name, s])), [NO_TASK, '', noTask]];
    writeFileSync(tsv, [`# generated by k usage --from ${FROM} --to ${TO} (gulnya/k-usage AC-2): a row per task and step, so the weights sum to the week's; never edited by hand`,
      ['task', 'step', 'weight', 'calls'].join('\t'), ...leaf.map(([t, s, r]) => [t, s, Math.round(r.weight), r.calls].join('\t'))].join('\n') + '\n');
  }

  const p = printer();
  const width = Math.max(NO_TASK.length, ...list.map((t) => t.name.length), ...list.flatMap((t) => t.steps.map((s) => s.name.length + 2)));
  const line = (name, r) => `${name.padEnd(width)}  ${`${(r.weight / 1e6).toFixed(1)}M`.padStart(8)}  ${`${(total ? (100 * r.weight) / total : 0).toFixed(1)}%`.padStart(6)}  ${String(r.calls).padStart(6)} calls`;
  p.log(`by task and step, heaviest first: weight in Opus-input tokens, share of the week's ${(total / 1e6).toFixed(1)}M, calls (${xs.length})`);
  for (const t of list) {
    p.log(line(t.name, t));
    for (const s of t.steps) p.log(line(`  ${s.name}`, s));
  }
  p.log(line(NO_TASK, noTask));
  return { total, calls: xs.length, tasks: list, noTask, text: p.text() };
}
